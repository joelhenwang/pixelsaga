"""Stage 3 diagnostic soak (owned by S3-SOAK-001).

Runs one canonical single-world 300-index scenario through HTTP
with scripted fakes, mirroring the S2 gate, and records growth
numbers every later Stage 3 lane designs against. No new
features; this lane reports, it does not gate.

The recall probe rides a communicate intent, not a resolver
effect: resolver effect facts feed narration, never observation
or memory rows, so only intent-derived content (attempt facts,
memory summaries) enters context assembly. Wren tells Ash the
probe topic in the opening phases; the audit checks whether
Wren's day-29 assembly still surfaces the resulting memory.

Evidence (regenerated by this test, gitignored):
``evidence/stage3-soak-v1/`` with scenario, growth, tables,
recall, and README files.
"""

